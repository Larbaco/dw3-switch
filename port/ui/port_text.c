static uint16_t rgb555(int r, int g, int b) {
    return (uint16_t)(((r >> 3) & 0x1f) | (((g >> 3) & 0x1f) << 5) |
                      (((b >> 3) & 0x1f) << 10));
}

static void put_glyph(uint16_t *fb, int fb_w, int fb_h, int x, int y,
                      char ch, uint16_t fg) {
    const uint8_t *glyph;
    int gx, gy;
    int idx;

    if (ch < 32 || ch > 126) {
        ch = '?';
    }
    idx = (int)ch - 32;
    glyph = dw3_port_font8x8[idx];
    for (gy = 0; gy < 8; gy++) {
        uint8_t bits = glyph[gy];
        int py = y + gy;
        if (py < 0 || py >= fb_h) {
            continue;
        }
        for (gx = 0; gx < 8; gx++) {
            int px = x + gx;
            if (px < 0 || px >= fb_w) {
                continue;
            }
            if (dw3_port_glyph_pixel(bits, gx)) {
                fb[py * fb_w + px] = fg;
            }
        }
    }
}

int dw3_port_text_draw_panel(int vram_x, int vram_y, int width, int height,
                             const char *const *lines, int line_count) {
    static uint16_t pixels[DW3_PORT_TEXT_MAX_W * DW3_PORT_TEXT_MAX_H];
    RECT rect;
    uint16_t bg = rgb555(16, 24, 48);
    uint16_t border = rgb555(200, 200, 220);
    uint16_t fg = rgb555(255, 255, 255);
    int x, y, i;
    int w = width;
    int h = height;

    if (lines == NULL || line_count <= 0) {
        return -1;
    }
    if (w < 32) {
        w = 32;
    }
    if (h < 24) {
        h = 24;
    }
    if (w > DW3_PORT_TEXT_MAX_W) {
        w = DW3_PORT_TEXT_MAX_W;
    }
    if (h > DW3_PORT_TEXT_MAX_H) {
        h = DW3_PORT_TEXT_MAX_H;
    }
    /* even width for LoadImage halfword pitch */
    w &= ~1;

    for (i = 0; i < w * h; i++) {
        pixels[i] = bg;
    }
    for (x = 0; x < w; x++) {
        pixels[x] = border;
        pixels[(h - 1) * w + x] = border;
    }
    for (y = 0; y < h; y++) {
        pixels[y * w] = border;
        pixels[y * w + (w - 1)] = border;
    }
    for (i = 0; i < line_count; i++) {
        const char *s = lines[i];
        int cx = 6;
        int cy = 6 + i * 10;
        if (s == NULL) {
            continue;
        }
        while (*s) {
            put_glyph(pixels, w, h, cx, cy, *s, fg);
            cx += 8;
            if (cx + 8 > w - 4) {
                break;
            }
            s++;
        }
    }

    setRECT(&rect, (short)vram_x, (short)vram_y, (short)w, (short)h);
    LoadImage(&rect, (u_long *)pixels);
    DrawSync(0);
    return 0;
}
