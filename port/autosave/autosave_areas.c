int dw3_autosave_area_of_mode(int mode) {
    int lo = 0;
    int hi = (int)(sizeof(k_areas) / sizeof(k_areas[0])) - 1;

    while (lo <= hi) {
        int mid = (lo + hi) / 2;

        if (k_areas[mid].mode == mode) {
            return k_areas[mid].area;
        }
        if (k_areas[mid].mode < mode) {
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    }
    return 0;
}
