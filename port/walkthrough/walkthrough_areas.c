/* STSTATUS_getArea(): the area of the current field map */
int dw3_wt_area_of_mode(int mode) {
    unsigned char v;

    if (mode < 0 || (mode & 0xFF) >= (int)sizeof(k_map_areas)) return WT_AREA_NONE;
    v = k_map_areas[mode & 0xFF];
    if (v == 0xFF) return WT_AREA_NONE;
    return v & 0x7F;
}

/* STSTATUS_getGameHalf() */
int dw3_wt_half_of_mode(int mode) {
    if (mode >= 0x2D7) return -1;
    return mode >= 0x270;
}
