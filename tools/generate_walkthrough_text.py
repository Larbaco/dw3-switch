#!/usr/bin/env python3
"""P6.35 embedded walkthrough text: port/walkthrough/text/<lang>.txt as C string
literals (port/walkthrough/walkthrough_text.inc), the way the P6.30 help does
(tools/generate_help_assets.py). The game reads no file at run time.

  python3 tools/generate_walkthrough_text.py          write the .inc
  python3 tools/generate_walkthrough_text.py --check  fail if it is out of date
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEXT_DIR = ROOT / 'port' / 'walkthrough' / 'text'
OUT = ROOT / 'port' / 'walkthrough' / 'walkthrough_text.inc'
LANGS = ('en', 'fr', 'de', 'es', 'it')  # the Options lettering order


def c_string(text: str) -> str:
    out = []
    for line in text.splitlines(keepends=True):
        s = line.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '')
        out.append('"%s"' % s)
    return '\n'.join(out) if out else '""'


def build() -> str:
    lines = ['/* Generated by tools/generate_walkthrough_text.py from port/walkthrough/text/<lang>.txt.',
             ' * Do not edit. UTF-8. */']
    for lang in LANGS:
        path = TEXT_DIR / f'{lang}.txt'
        text = path.read_text(encoding='utf-8') if path.exists() else ''
        lines.append('static const char wt_text_%s[] =' % lang)
        lines.append(c_string(text) + ';')
    return '\n'.join(lines) + '\n'


def main(argv: list[str]) -> int:
    text = build()
    if '--check' in argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            print('walkthrough_text.inc is out of date: run tools/generate_walkthrough_text.py')
            return 1
        return 0
    OUT.write_text(text, encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
