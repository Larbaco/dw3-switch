#!/usr/bin/env python3
"""P5.5: (re)generate port/sweep/stage_list.inc, the stage sweep's table of
game modes and WSTAG numbers, from the decomp's FIELDSTG_stages (US and EU).

  tools/gen_sweep_stages.py           write port/sweep/stage_list.inc
  tools/gen_sweep_stages.py --check   exit 1 when the file is stale

The US and the EU table list the same modes with the same stages (checked
here); the European extra chapter's FIELDSTG_extraStages are not in the set.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "vendor/dw3_decomp/src/field/field_mode/data/fieldstg.c"
OUT = ROOT / "port/sweep/stage_list.inc"
ENTRY = re.compile(r"\s*\{(\d+),\s*(\d+),\s*WSTAG(\d+)_startStage\}")


def tables(lines: list[str]) -> list[dict[int, int]]:
    """One {mode: wstag number} per `StageEntry FIELDSTG_stages[]` definition."""
    out: list[dict[int, int]] = []
    cur: dict[int, int] | None = None
    for line in lines:
        if line.startswith("StageEntry FIELDSTG_stages[]"):
            cur = {}
            out.append(cur)
        elif line.startswith("};"):
            cur = None
        elif cur is not None:
            m = ENTRY.match(line)
            if m:
                cur[int(m.group(1))] = int(m.group(3))
    return out


def render() -> str:
    t = tables(SRC.read_text().splitlines())
    if len(t) != 2 or t[0] != t[1]:
        sys.exit("US and EU FIELDSTG_stages differ (or were not found): "
                 "the sweep table needs a per-version split")
    rows = ["/* Generated by tools/gen_sweep_stages.py from FIELDSTG_stages "
            "(US and EU are the\n * same list). Do not edit. { game mode, "
            "WSTAG number }, in table order. */"]
    for mode, num in t[0].items():
        rows.append("{ 0x%03X, %d }," % (mode, num))
    return "\n".join(rows) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("port/sweep/stage_list.inc is stale: run "
                  "tools/gen_sweep_stages.py")
            return 1
        return 0
    OUT.write_text(text)
    print("wrote", OUT, text.count("\n") - 2, "stages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
