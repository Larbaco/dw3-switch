#!/usr/bin/env python3
"""P10.6: draw the Switch button glyphs (A B X Y L R ZL ZR) for the port.

The art is original and made for this project (assets/glyphs/PROVENANCE.md):
a disc built from a distance test, and letters from the small pixel bitmaps in
this file. Nothing is read from the game, the console or any other artwork.

  python3 tools/generate_switch_glyphs.py            write assets/glyphs/*.png
                                                     and port/options/switch_glyph_art.inc
  python3 tools/generate_switch_glyphs.py --check    fail if either is out of date
  python3 tools/generate_switch_glyphs.py --ascii    print every glyph

Format of a glyph: 12x12, indexed by *role*, not by colour (the game's font
palette is not touched; the port maps the roles to the palette indices of the
disc at run time, port/options/switch_glyphs.c):

  0 clear   1 outline (the rim)   2 body (the fill)   3 letter   4 shade (the
  drop shadow under the rim)

The PNG has four fixed role colours (below) so a glyph can be looked at and
edited in any image program; the loader reads the role back from the colour.
"""
from __future__ import annotations

import argparse
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "assets" / "glyphs"
INC_PATH = ROOT / "port" / "options" / "switch_glyph_art.inc"

W = H = 12
CLEAR, OUTLINE, BODY, LETTER, SHADE = range(5)
# The fixed role colours of the PNG (index = role; index 0 is transparent).
ROLE_RGB = [(0, 0, 0), (224, 224, 224), (40, 40, 48), (255, 255, 255), (112, 112, 120)]
# File name (without .png) in glyph order; the C enum has the same order.
NAMES = ["a", "b", "x", "y", "l", "r", "zl", "zr"]

# Letters, 5 wide x 7 tall; '#' is a lit pixel.
BIG = {
    "a": [".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    "b": ["####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."],
    "x": ["#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#"],
    "y": ["#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..", "..#.."],
    "l": ["#....", "#....", "#....", "#....", "#....", "#....", "#####"],
    "r": ["####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#"],
}
# Letters of the two-letter glyphs, 3 wide x 5 tall.
SMALL = {
    "z": ["###", "..#", ".#.", "#..", "###"],
    "l": ["#..", "#..", "#..", "#..", "###"],
    "r": ["##.", "#.#", "##.", "#.#", "#.#"],
}

# The disc: pixel centres at (5, 5), radius 5.5 -> 11 x 11 pixels in columns
# 0..10 and rows 0..10; the shade is the disc again one row lower (row 11).
CX = CY = 5
R2 = 5.5 * 5.5


def _inside(x: int, y: int) -> bool:
    return 0 <= x < W and 0 <= y < H and (x - CX) ** 2 + (y - CY) ** 2 <= R2


def _disc() -> list[list[int]]:
    g = [[CLEAR] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            if _inside(x, y):
                edge = any(not _inside(x + dx, y + dy)
                           for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
                g[y][x] = OUTLINE if edge else BODY
    for y in range(H):
        for x in range(W):
            if g[y][x] == CLEAR and _inside(x, y - 1):
                g[y][x] = SHADE
    return g


def _stamp(g, rows, x0, y0):
    for dy, row in enumerate(rows):
        for dx, c in enumerate(row):
            if c == "#":
                g[y0 + dy][x0 + dx] = LETTER


def glyph(name: str) -> list[list[int]]:
    g = _disc()
    if name in BIG:
        _stamp(g, BIG[name], 3, 2)         # 5 x 7 inside the 9 x 9 body
    else:
        _stamp(g, SMALL[name[0]], 2, 3)    # two 3 x 5 letters and a 1 px gap
        _stamp(g, SMALL[name[1]], 6, 3)
    return g


def ascii_art(g) -> str:
    return "\n".join("".join(" .:#s"[v] if v != SHADE else "s" for v in row) for row in g)


def _chunk(tag: bytes, data: bytes) -> bytes:
    return (struct.pack(">I", len(data)) + tag + data +
            struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))


def png_bytes(g) -> bytes:
    """An 8-bit palette PNG, 12 x 12, five palette entries, entry 0 transparent."""
    raw = b"".join(b"\x00" + bytes(row) for row in g)
    plte = b"".join(bytes(c) for c in ROLE_RGB)
    return (b"\x89PNG\r\n\x1a\n" +
            _chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 3, 0, 0, 0)) +
            _chunk(b"PLTE", plte) +
            _chunk(b"tRNS", b"\x00") +
            _chunk(b"IDAT", zlib.compress(raw, 9)) +
            _chunk(b"IEND", b""))


def inc_text(glyphs) -> str:
    out = ["/* Generated by tools/generate_switch_glyphs.py from the glyph art in",
           " * assets/glyphs/ (original, see PROVENANCE.md there). Do not edit.",
           " * One string of 12 role digits per row (0 clear, 1 outline, 2 body,",
           " * 3 letter, 4 shade), in the order of the DW3_GLYPH_* enum. */"]
    for n, g in zip(NAMES, glyphs):
        out.append("{ /* %s */" % n.upper())
        for row in g:
            out.append('    "%s"' % "".join(str(v) for v in row))
        out.append("},")
    return "\n".join(out) + "\n"


def build() -> dict[Path, bytes]:
    glyphs = [glyph(n) for n in NAMES]
    files = {OUT_DIR / f"{n}.png": png_bytes(g) for n, g in zip(NAMES, glyphs)}
    files[INC_PATH] = inc_text(glyphs).encode()
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed files differ")
    ap.add_argument("--ascii", action="store_true", help="print the glyphs and stop")
    a = ap.parse_args(argv)
    if a.ascii:
        for n in NAMES:
            print(f"-- {n}\n{ascii_art(glyph(n))}")
        return 0
    files = build()
    if a.check:
        bad = [str(p.relative_to(ROOT)) for p, data in files.items()
               if not p.exists() or p.read_bytes() != data]
        if bad:
            print("out of date (run tools/generate_switch_glyphs.py):", *bad, sep="\n  ")
            return 1
        print(f"ok: {len(files)} generated files match")
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for p, data in files.items():
        p.write_bytes(data)
        print("wrote", p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
