#!/usr/bin/env python3
"""Generate weak stubs for WSTAG_* symbols declared in include/field/stages.h
that are not provided by linked stage objects (P3.2).

  gen_stage_stubs.py --stages-h PATH --exclude WSTAG780,WSTAG785,WSTAG260 -o stubs.c
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

TASK_FN = re.compile(
    r"^struct\s+Task\s*\*\s*(WSTAG\d+_[A-Za-z0-9]+)\s*\(([^;]*)\)\s*;", re.M
)
VOID_PTR_FN = re.compile(
    r"^void\s*\*\s*(WSTAG\d+_[A-Za-z0-9]+)\s*\(([^;]*)\)\s*;", re.M
)
S32_FN = re.compile(r"^s32\s+(WSTAG\d+_[A-Za-z0-9]+)\s*\(([^;]*)\)\s*;", re.M)
VOID_FN = re.compile(r"^void\s+(WSTAG\d+_[A-Za-z0-9]+)\s*\(([^;]*)\)\s*;", re.M)
SCRIPT = re.compile(r"^extern\s+s16\s+(WSTAG260_script\d+)\s*\[\s*\]\s*;", re.M)


def stub_params(params: str) -> str:
    params = params.strip()
    if not params or params == "void":
        return "void"
    parts = [p.strip() for p in params.split(",") if p.strip()]
    out = []
    for i, p in enumerate(parts):
        m = re.match(r"^(.*\S)(\s*\*+\s*|\s+)([A-Za-z_][A-Za-z0-9_]*)$", p)
        if m:
            ty = (m.group(1) + m.group(2)).strip()
        else:
            ty = p
        out.append(f"{ty} a{i}")
    return ", ".join(out)


def emit(lines: list[str], seen: set[str], exclude: set[str], name: str, ret: str, params: str, body: str) -> None:
    stage = name.split("_", 1)[0]
    if stage in exclude or name in seen:
        return
    seen.add(name)
    plist = stub_params(params)
    lines.append(f"{ret} {name}({plist}) __attribute__((weak));")
    lines.append(f"{ret} {name}({plist}) {{ {body} }}")
    lines.append("")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--stages-h", required=True)
    ap.add_argument("--exclude", default="", help="comma-separated stage prefixes to skip")
    ap.add_argument("-o", required=True)
    args = ap.parse_args()

    exclude = {p.strip().upper() for p in args.exclude.split(",") if p.strip()}
    text = Path(args.stages_h).read_text()
    seen: set[str] = set()
    lines = [
        "/* Generated by tools/gen_stage_stubs.py — do not edit. */",
        "#ifndef PORT_HOST",
        '#error "stage_stubs.c is host-only"',
        "#endif",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct Task Task;",
        "typedef int32_t s32;",
        "typedef int16_t s16;",
        "",
    ]

    for m in TASK_FN.finditer(text):
        emit(lines, seen, exclude, m.group(1), "Task *", m.group(2), "return (Task *)0;")
    for m in VOID_PTR_FN.finditer(text):
        emit(lines, seen, exclude, m.group(1), "void *", m.group(2), "return (void *)0;")
    for m in S32_FN.finditer(text):
        emit(lines, seen, exclude, m.group(1), "s32", m.group(2), "return 0;")
    for m in VOID_FN.finditer(text):
        emit(lines, seen, exclude, m.group(1), "void", m.group(2), "return;")

    if "WSTAG260" not in exclude:
        for m in SCRIPT.finditer(text):
            name = m.group(1)
            if name in seen:
                continue
            seen.add(name)
            lines.append(f"s16 {name}[1] __attribute__((weak)) = {{ 0 }};")
            lines.append("")

    Path(args.o).parent.mkdir(parents=True, exist_ok=True)
    Path(args.o).write_text("\n".join(lines) + "\n")
    print(f"gen_stage_stubs: wrote {len(seen)} symbols → {args.o}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
